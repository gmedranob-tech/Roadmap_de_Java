package semana01_fundamentos;

public class OperacionesMatematicas {

	public static void main(String[] args) {

		// Ejercicio 1: Potencia
		System.out.println("===== EJERCICIO 1 =====");

		double resultadoPotencia = Math.pow(5, 2);

		System.out.println("5 elevado a 2 = " + resultadoPotencia);

		System.out.println();

		// Ejercicio 2: Raíz cuadrada
		System.out.println("===== EJERCICIO 2 =====");

		double resultadoRaiz = Math.sqrt(81);

		System.out.println("Raíz cuadrada de 81 = " + resultadoRaiz);

		System.out.println();

		// Ejercicio 3: Número aleatorio
		System.out.println("===== EJERCICIO 3 =====");

		double numeroAleatorio = Math.random();

		System.out.println("Número aleatorio = " + numeroAleatorio);

	}

}


package semana02_control_flujo;

public class Loops {

	public static void main(String[] args) {

		System.out.println("===== EJERCICIO 1 =====");

		for (int i = 1; i <= 5; i++) {

			System.out.println(i);

		}

		System.out.println();

		System.out.println("===== EJERCICIO 2 =====");

		int contador = 1;

		while (contador <= 5) {

			System.out.println(contador);

			contador++;

		}

	}

}
